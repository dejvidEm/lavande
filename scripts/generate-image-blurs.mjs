/**
 * Vygeneruje maličké blur placeholdery pre štúdiové fotky.
 * node scripts/generate-image-blurs.mjs
 */
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const DIR = "public/images/lavande";
const OUT = "src/data/image-blurs.ts";

const files = (await readdir(DIR))
  .filter((name) => name.endsWith(".jpg"))
  .sort();

const entries = [];

for (const name of files) {
  const src = path.join(DIR, name);
  const { width, height } = await sharp(src).metadata();
  const blurWidth = 16;
  const blurHeight = Math.max(1, Math.round((height / width) * blurWidth));
  const buffer = await sharp(src)
    .rotate()
    .resize(blurWidth, blurHeight, { fit: "fill" })
    .webp({ quality: 40, effort: 6 })
    .toBuffer();

  const key = `/images/lavande/${name}`;
  const dataUrl = `data:image/webp;base64,${buffer.toString("base64")}`;
  entries.push({ key, dataUrl, bytes: buffer.length });
}

const body = entries
  .map(({ key, dataUrl }) => `  "${key}": "${dataUrl}",`)
  .join("\n");

await writeFile(
  OUT,
  `/** Auto-generated by scripts/generate-image-blurs.mjs — neupravovať ručne. */\n` +
    `export const imageBlurs: Record<string, string> = {\n${body}\n};\n`
);

const total = entries.reduce((sum, item) => sum + item.bytes, 0);
console.log(`✓ ${OUT}`);
for (const item of entries) {
  console.log(`  ${item.key.split("/").at(-1)}  ${item.bytes} B`);
}
console.log(`  spolu ${total} B`);
